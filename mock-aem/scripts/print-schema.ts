/**
 * Writes the generated schema to mock-aem/schema.graphql so tools (GraphQL Codegen, the VS Code
 * GraphQL extension, gql.tada) can use it without the mock server running.
 *
 *   npm run mock:schema
 */
import fs from "node:fs";
import path from "node:path";
import { printSchema } from "graphql";
import { createSchema } from "../src/engine";

const target = path.resolve(process.cwd(), "mock-aem/schema.graphql");
const header = `# Generated by "npm run mock:schema" from mock-aem/src/models.ts — do not edit by hand.
# Real AEM serves the same thing at /content/cq:graphql/<config>/endpoint.GQLschema
`;
fs.writeFileSync(target, `${header}\n${printSchema(createSchema())}\n`);
console.log(`Schema written to ${path.relative(process.cwd(), target)}`);
