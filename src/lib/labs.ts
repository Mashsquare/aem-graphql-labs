/**
 * The lab catalogue. Each lab has two modules:
 *   src/labs/<slug>/       PROMPT.md + the starter files you edit
 *   src/solutions/<slug>/  SOLUTION.md + the reference implementation
 */

export type LabPart = "foundations" | "clients" | "aem" | "classic" | "sling";

export interface LabMeta {
  slug: string;
  number: number;
  title: string;
  summary: string;
  part: LabPart;
  api: string;
  tools: string[];
  concepts: string[];
  minutes: number;
  /** Files you edit, relative to src/labs/<slug>/ */
  files: string[];
  /** Files shown on the solution page, relative to src/solutions/<slug>/ */
  solutionFiles: string[];
  /** Command that checks your work, if the lab has automated checks. */
  check?: string;
  /** Extra routes that belong to the lab (e.g. the capstone pages). */
  routes?: { label: string; href: string; solution?: boolean }[];
}

