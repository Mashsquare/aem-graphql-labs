export function getLab(slug: string): LabMeta | undefined {
  return labs.find((lab) => lab.slug === slug);
}

export function neighbours(slug: string): { previous?: LabMeta; next?: LabMeta } {
  const index = labs.findIndex((lab) => lab.slug === slug);
  return { previous: labs[index - 1], next: labs[index + 1] };
}
